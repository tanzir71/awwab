export function prayerCityLabel(city: City, t: (key: string) => string) {
  const preset = cities.find(item => item.name === city.name && item.latitude === city.latitude
    && item.longitude === city.longitude && item.timeZone === city.timeZone);
  return preset ? t(`settingsCity${preset.name.replace(/ /g, "")}`) : city.name;
}

