"""Regenerate the small picker fonts from the pinned Fontsource packages."""

import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
packages = root / "node_modules/@fontsource-variable"
inventory = root / "handovers/H2-languages-paths-arabic-help/data/locales.json"
locales = json.loads(inventory.read_text(encoding="utf8"))["locales"]
fonts = json.loads((root / "scripts/locale-fonts.json").read_text(encoding="utf8"))
output = root / "src/assets/locale-names"
output.mkdir(parents=True, exist_ok=True)

css = []
for script, source in fonts.items():
    # Cluster shaping needs the base letters as well as combining marks from each name.
    characters = set("".join(locale["native"] for locale in locales if locale["script"] == script))
    if script == "Latn":
        base = TTFont(packages / "noto-sans/files/noto-sans-latin-wght-normal.woff2")
        characters -= set(map(chr, base.getBestCmap()))
    family = f"Awwab Names {script}"
    for block in source["subsets"]:
        package = source["package"]
        font = TTFont(packages / package / "files" / f"{package}-{block}-wght-normal.woff2", recalcTimestamp=False)
        available = characters.intersection(map(chr, font.getBestCmap()))
        options = subset.Options()
        options.name_IDs = ["*"]
        options.layout_features = ["*"]
        cutter = subset.Subsetter(options=options)
        cutter.populate(text="".join(sorted(available)))
        cutter.subset(font)
        for entry in font["name"].names:
            if entry.nameID in (1, 3, 4, 6, 16, 18, 21, 25):
                name = family.replace(" ", "") if entry.nameID in (6, 25) else family
                entry.string = name.encode(entry.getEncoding())
        filename = f"{script.lower()}-{block}.woff2"
        font.save(output / filename)
        ranges = ", ".join(f"U+{ord(character):04X}" for character in sorted(available))
        css.extend([
            "@font-face {", f'  font-family: "{family}";',
            f'  src: url("./assets/locale-names/{filename}") format("woff2");',
            "  font-style: normal;", "  font-weight: 100 900;",
            "  font-display: swap;", f"  unicode-range: {ranges};", "}",
        ])
        characters -= available
    if characters - set(" -–()'’ʼ"):
        raise ValueError(f"Missing picker glyphs for {script}: {sorted(characters)}")
    css.append(f'[data-locale-name="{script}"] {{ font-family: "{family}", var(--font-body), sans-serif; }}')
    if script == "Latn":
        for mode, body, display, fallback in [
            ("adult", "Noto Sans Variable", "Noto Serif Variable", "serif"),
            ("maktab", "Nunito Variable", "Baloo 2 Variable", "sans-serif"),
        ]:
            css.extend([
                f':root[data-ui-script="{script}"][data-mode="{mode}"],',
                f':root[data-ui-script="{script}"] [data-theme-preview="{mode}"] {{',
                f'  --font-body: "{body}", "Awwab UI {script}", sans-serif;',
                f'  --font-display: "{display}", "Awwab UI {script}", {fallback};',
                "}",
            ])
    else:
        css.extend([
            f':root[data-ui-script="{script}"][data-mode],',
            f':root[data-ui-script="{script}"] [data-theme-preview] {{',
            f'  --font-body: "Awwab UI {script}", "Noto Sans Variable", sans-serif;',
            "  --font-display: var(--font-body);",
            "}",
        ])

(root / "src/fonts-locale-names.css").write_text("/* Generated by scripts/build-locale-name-fonts.py */\n" + "\n".join(css) + "\n", encoding="utf8", newline="\n")
